def pf_word(word, wide=""):
    rows = []
    for gr in range(5):
        rows.append(".".join((PF_WIDE[ch] if ch in wide else FONT[ch])[gr] for ch in word))
    width = len(rows[0])
    assert width <= 40, word
    left = (40 - width) // 2
    return ["." * left + r + "." * (40 - width - left) for r in rows]


TITLE_LINES = 178


def build_bank6():
    lines = [{"pf": "." * 40, "pfc": 0, "bk": 0} for _ in range(TITLE_LINES)]
    for i, row in enumerate(pf_word("HOMELESS", wide="M")):
        for dy in range(6):
            lines[10 + i * 6 + dy] = {"pf": row, "pfc": col((1, 7 - i)), "bk": 0}
    for i, row in enumerate(pf_word("INSURGENCY")):
        for dy in range(6):
            lines[46 + i * 6 + dy] = {"pf": row, "pfc": col((3, 6 - i)), "bk": 0}
    skyline = [
        (112, "..........................#####........."),
        (118, "...####.................##########......"),
        (124, "...####.......#####.....##########...###"),
        (132, "######...#######.#####..##########..####"),
        (140, "######..################################"),
        (148, "########################################"),
    ]
    for y in range(100, 166):
        bits = "." * 40
        for y0, b in skyline:
            if y >= y0:
                bits = b
        lines[y] = {"pf": bits, "pfc": col((0, 0)), "bk": col((6, min(2, (y - 100) // 24)))}
    for y in range(166, 170):
        lines[y] = {"pf": "#" * 40, "pfc": col((0, 2)), "bk": 0}
    for y in range(86, 96):     # text rows: playfield must be empty
        assert lines[y]["pf"] == "." * 40
    a = Asm("bank 6 data")
    regs = [row_to_pf([ch == "#" for ch in ln["pf"]]) for ln in lines]
    for i, name in enumerate(("TitlePF0L", "TitlePF1L", "TitlePF2L",
                              "TitlePF0R", "TitlePF1R", "TitlePF2R")):
        a.table(name, [r[i] for r in regs], align=True)
    a.table("TitlePFC", [ln["pfc"] for ln in lines], align=True)
    a.table("TitleBK", [ln["bk"] for ln in lines], align=True)
    a.equ("TITLE_TEXT1_LINE", 86)
    a.equ("TITLE_LINES", TITLE_LINES)
    a.equ("COL_TITLE_TEXT", col((0, 6)))
    a.equ("COL_PRESS_FIRE", col((1, 6)))
    a.save("bank6_data.asm")


def main():
    with open(os.path.join(ROOT, "assets", "rooms", "city.txt")) as f:
        patterns, rooms, start = parse_city(f.read())
    build_bank0(patterns, rooms, start)
    build_bank1()
    build_bank6()


if __name__ == "__main__":
    main()
