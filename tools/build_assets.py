def pf_word(word, wide=""):
    rows = []
    for gr in range(5):
        rows.append(".".join((PF_WIDE[ch] if ch in wide else FONT[ch])[gr] for ch in word))
    width = len(rows[0])
    assert width <= 40, word
    left = (40 - width) // 2
    return ["." * left + r + "." * (40 - width - left) for r in rows]


