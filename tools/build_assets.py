# bank 1: city sprites and background
# ---------------------------------------------------------------------------

def sprite_rows(art, colors):
    """Bottom-to-top graphics and color bytes for a sprite."""
    gfx, cols = [], []
    for row in reversed(art):
        keys = {ch for ch in row if ch != "."}
        assert len(keys) <= 1, row
        gfx.append(sum(1 << (7 - i) for i, ch in enumerate(row.ljust(8, ".")) if ch != "."))
        cols.append(col(colors[keys.pop()]) if keys else 0)
    return gfx, cols


def build_bank1():
    a = Asm("bank 1 data")
    city = [
        ("Player", sprites.PLAYER_TOP, sprites.PLAYER_COLORS),
        ("Shelter", sprites.SIGN_SHELTER, {"W": (10, 7)}),
        ("Food", sprites.SIGN_FOOD, {"F": (0, 6), "M": (2, 5)}),
    ]
    a.comment("Each sprite has SPRITE_PAD zero rows on both sides so the kernel")
    a.comment("can index (ptr),y for every line pair without a range check.")
    a.label("GfxStart")
    a.bytes([0] * SPRITE_PAD)
    for name, art, colors in city:
        gfx, _ = sprite_rows(art, colors)
        a.table(f"{name}Gfx", gfx)
        a.equ(f"{name.upper()}_H", len(gfx))
        a.bytes([0] * SPRITE_PAD)
    a.label("ColStart")
    a.bytes([0] * SPRITE_PAD)
    for name, art, colors in city:
        _, cols = sprite_rows(art, colors)
        a.table(f"{name}Col", cols)
        a.bytes([0] * SPRITE_PAD)
    a.equ("BlankGfx", "GfxStart")
    a.equ("BlankCol", "ColStart")

    # background per line pair, indexed by pair (77 = top of screen)
    asphalt, sidewalk = col((0, 1)), col((0, 3))
    bk = [asphalt] * SCREEN_PAIRS
    for top in (65, 29):            # street pairs top..top-17
        for p in (top - 1, top - 2, top - 15, top - 16):
            bk[p] = sidewalk         # sidewalks start one pair in from the street edge
    a.table("CityBK", bk, align=True)
    dash = half_to_pf([ch == "#" for ch in "..##" * 5])
    a.equ("DASH_PF0", dash[0])
    a.equ("DASH_PF1", dash[1])
    a.equ("DASH_PF2", dash[2])
    a.equ("COL_DASH", col((1, 5)))
    a.equ("COL_HUD", col((1, 6)))
    a.equ("COL_ENERGY", col((12, 4)))
    a.save("bank1_data.asm")


