#!/usr/bin/env python3
"""Generate src/generated/*.asm from assets/ (font, sprites, city map, title).

Usage: python3 tools/build_assets.py
"""
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "assets"))
sys.path.insert(0, os.path.join(ROOT, "tools"))

import sprites  # noqa: E402
from font import FONT, PF_WIDE  # noqa: E402
from rooms import parse_city, pattern_cols  # noqa: E402

OUT = os.path.join(ROOT, "src", "generated")

CHARSET = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ.,!?-$%'/:+"
SCREEN_PAIRS = 78         # city map area: 156 lines as 78 line pairs
SPRITE_PAD = 80           # zero rows around each sprite (pairs index -77..+77)
ENERGY_BLOCKS = 18        # energy bar length in playfield blocks


def col(hl):
    hue, lum = hl
    return (hue << 4) | (lum << 1)


def text_codes(s, width=12):
    s = s.center(width)
    assert len(s) == width, s
    return [CHARSET.index(ch) for ch in s]


def half_to_pf(cols):
    """20 booleans (left to right) -> (PF0, PF1, PF2) register bytes."""
    pf0 = sum(1 << (4 + i) for i in range(4) if cols[i])
    pf1 = sum(1 << (7 - i) for i in range(8) if cols[4 + i])
    pf2 = sum(1 << i for i in range(8) if cols[12 + i])
    return pf0, pf1, pf2


def row_to_pf(bits40):
    return half_to_pf(bits40[:20]) + half_to_pf(bits40[20:])


class Asm:
    def __init__(self, title):
        self.lines = [f"; Generated by tools/build_assets.py - {title}. Do not edit.", ""]

    def label(self, name):
        self.lines.append(name)

    def bytes(self, values, per_line=16):
        values = list(values)
        for i in range(0, len(values), per_line):
            chunk = values[i:i + per_line]
            self.lines.append("    .byte " + ",".join(f"${v & 0xFF:02X}" for v in chunk))

    def table(self, name, values, align=False):
        if align:
            self.lines.append("    ALIGN 256")
        self.label(name)
        self.bytes(values)

    def equ(self, name, value):
        self.lines.append(f"{name} = {value}")

    def comment(self, text):
        self.lines.append(f"; {text}")

    def save(self, filename):
        os.makedirs(OUT, exist_ok=True)
        with open(os.path.join(OUT, filename), "w") as f:
            f.write("\n".join(self.lines) + "\n")


# ---------------------------------------------------------------------------
# bank 0: font, strings, rooms, energy bar
# ---------------------------------------------------------------------------

def build_bank0(patterns, rooms, start):
    a = Asm("bank 0 data")
    # 4-pixel glyphs: FontHi holds the glyph in the high nibble, FontLo in the
    # low nibble, so a byte for two characters is FontHi[l] | FontLo[r].
    hi, lo = [], []
    for ch in CHARSET:
        for row in FONT[ch]:
            bits = sum(1 << (2 - i) for i, b in enumerate(row) if b == "#")  # 3 bits
            hi.append(bits << 5)   # glyph in bits 7-5, bit 4 blank (spacing)
            lo.append(bits << 1)   # glyph in bits 3-1, bit 0 blank
    assert len(hi) <= 256
    a.table("FontHi", hi)
    a.table("FontLo", lo)
    a.equ("CHAR_SPACE", CHARSET.index(" "))
    a.equ("CHAR_0", CHARSET.index("0"))
    a.equ("CHAR_DOLLAR", CHARSET.index("$"))
    a.equ("CHAR_DOT", CHARSET.index("."))
    a.equ("CHAR_SLASH", CHARSET.index("/"))
    a.equ("CHAR_QUESTION", CHARSET.index("?"))
    for name, s in (("StrAct1", "ACT I: RALLY"), ("StrPressFire", "PRESS FIRE")):
        a.table(name, text_codes(s))

    # building band patterns
    names = sorted(patterns)
    pf = [row_to_pf(pattern_cols(*patterns[n])) for n in names]
    a.comment("building band patterns: " + " ".join(names))
    a.table("PatPF0", [p[0] for p in pf])
    a.table("PatPF1", [p[1] for p in pf])
    a.table("PatPF2", [p[2] for p in pf])
    a.table("PatCtrl", [1 if patterns[n][0] == "M" else 0 for n in names])
    # 40 columns as 5 bytes per pattern (bit 7 = leftmost) for wall checks
    bits = []
    for n in names:
        cols = pattern_cols(*patterns[n])
        bits += [sum(1 << (7 - i) for i in range(8) if cols[k * 8 + i]) for k in range(5)]
    a.table("PatBits", bits)
    a.table("BitMask", [0x80 >> i for i in range(8)])
    flat = [room for row in rooms for room in row]
    for i, band in enumerate("ABC"):
        a.table(f"RoomBand{band}", [names.index(r["bands"][i]) for r in flat])
    a.table("RoomSign", [{"": 0, "S": 1, "F": 2}[r["sign"]] for r in flat])
    a.equ("START_ROOM", start[0] * 8 + start[1])
    # roof colors per (map row + band) & 7: brick, concrete, teal, slate...
    a.table("BandColors", [col(c) for c in
                           [(3, 2), (15, 3), (10, 2), (4, 2), (13, 2), (15, 2), (9, 2), (2, 3)]])

    # energy bar: blocks 1..18 from the left edge (column 0 left empty)
    p0, p1, p2 = [], [], []
    for n in range(ENERGY_BLOCKS + 1):
        cols = [0 < i <= n for i in range(20)]
        v = half_to_pf(cols)
        p0.append(v[0]); p1.append(v[1]); p2.append(v[2])
    a.table("BarPF0", p0)
    a.table("BarPF1", p1)
    a.table("BarPF2", p2)
    a.equ("ENERGY_BLOCKS", ENERGY_BLOCKS)
    a.save("bank0_data.asm")


