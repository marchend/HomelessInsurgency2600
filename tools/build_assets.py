def alley_x(mode, half):
    """x of a sprite standing in the band's first vertical street (0 = none)."""
    cols = pattern_cols(mode, half)
    for c in range(40):
        if not cols[c]:
            return c * 4 + 4
    return 0


def place_homeless(patterns, rooms, start):
    """Deterministically spread HOMELESS_COUNT people over rooms and slots.

    Shelter rooms get a crowd (every free slot); the start room always has
    one in its top street so there is someone to talk to right away; the rest
    go one per room. Returns {(room, slot): person}.
    """
    import random
    rnd = random.Random(2600)
    flat = [room for row in rooms for room in row]

    def free_slots(i):
        r = flat[i]
        out = [1, 3]
        for slot, band in zip(ALLEY_SLOTS, r["bands"]):
            if slot == 2 and r["sign"]:
                continue
            if alley_x(*patterns[band]):
                out.append(slot)
        return out

    placed = {}
    start_room = start[0] * 8 + start[1]
    placed[(start_room, 1)] = len(placed)
    for i, r in enumerate(flat):
        if r["sign"] == "S":
            for slot in free_slots(i):
                if (i, slot) not in placed and len(placed) < HOMELESS_COUNT:
                    placed[(i, slot)] = len(placed)
    others = [i for i in range(64) if not any(k[0] == i for k in placed)]
    rnd.shuffle(others)
    for i in others:
        if len(placed) == HOMELESS_COUNT:
            break
        placed[(i, rnd.choice(free_slots(i)))] = len(placed)
    assert len(placed) == HOMELESS_COUNT
    return placed


def place_items(patterns, rooms, start, placed):
    """Weapons lie in middle-band alleys of rooms with nothing else there.
    Returns {room: weapon number 1..ITEM_COUNT}."""
    import random
    rnd = random.Random(1977)
    flat = [room for row in rooms for room in row]
    start_room = start[0] * 8 + start[1]
    spots = [i for i, r in enumerate(flat)
             if not r["sign"] and alley_x(*patterns[r["bands"][1]])
             and (i, 2) not in placed and i != start_room]
    rnd.shuffle(spots)
    return {room: n + 1 for n, room in enumerate(spots[:ITEM_COUNT])}


def build_bank0(patterns, rooms, start, placed, items):
    a = Asm("bank 0 data")
    hi, lo = font_tables()
    a.table("FontHi", hi)
    a.table("FontLo", lo)
    a.comment("glyph offsets (character code * 5), as the composer wants them")
    for name, ch in (("SPACE", " "), ("0", "0"), ("DOLLAR", "$"), ("DOT", "."),
                     ("SLASH", "/"), ("QUESTION", "?")):
        a.equ(f"GLYPH_{name}", CHARSET.index(ch) * 5)
    for name, s in (("StrAct1", "ACT I: RALLY"), ("StrPressFire", "PRESS FIRE")):
        a.table(name, glyphs(s))
    # fight footer: "WEAPN CREW N" - weapon names, 5 glyphs each, then "CREW "
    names = []
    for wname, _ in outcomes.WEAPONS:
        assert len(wname) <= 5, wname
        names += glyphs(wname, 5, center=False)
    a.table("WeaponGlyphs", names)
    a.table("CrewGlyphs", glyphs(" CREW ", 6, center=False))

    # building band patterns
    names = sorted(patterns)
    pf = [row_to_pf(pattern_cols(*patterns[n])) for n in names]
    a.comment("building band patterns: " + " ".join(names))
    a.table("PatPF0", [p[0] for p in pf])
    a.table("PatPF1", [p[1] for p in pf])
    a.table("PatPF2", [p[2] for p in pf])
    a.table("PatCtrl", [1 if patterns[n][0] == "M" else 0 for n in names])
    # 40 columns as 5 bytes per pattern (bit 7 = leftmost) for wall checks
    bits = []
    for n in names:
        cols = pattern_cols(*patterns[n])
        bits += [sum(1 << (7 - i) for i in range(8) if cols[k * 8 + i]) for k in range(5)]
    a.table("PatBits", bits)
    a.table("BitMask", [0x80 >> i for i in range(8)])
    flat = [room for row in rooms for room in row]
    for i, band in enumerate("ABC"):
        a.table(f"RoomBand{band}", [names.index(r["bands"][i]) for r in flat])
    a.table("RoomSign", [{"": 0, "S": 1, "F": 2}[r["sign"]] for r in flat])
    a.table("RoomItem", [items.get(i, 0) for i in range(64)])
    a.equ("ITEM_COUNT", ITEM_COUNT)
    a.table("PatAlleyX", [alley_x(*patterns[n]) for n in names])
    for slot in range(5):
        a.table(f"RoomSlot{slot}Person", [placed.get((i, slot), NO_PERSON) for i in range(64)])
    a.equ("HOMELESS_COUNT", HOMELESS_COUNT)
    a.equ("NO_PERSON", NO_PERSON)
    a.table("SlotY", SLOT_Y)
    # mid-screen P1 reposition (bank1 REPOSITION_B): delay loop count and
    # fine motion for each x; coarse 1-10 puts RESP1 at x = 15 * coarse
    coarse, fine = [], []
    for x in range(160):
        c = min(10, max(1, (x + 7) // 15))
        off = 15 * c - x                    # positive = HMOVE moves left
        assert -8 <= off <= 7 or x < 8 or x > 158, x
        off = max(-8, min(7, off))
        coarse.append(c)
        fine.append((off & 0xF) << 4)
    a.table("SlotCoarseTab", coarse)
    a.table("SlotFineTab", fine)

    # sprite base addresses per slot kind (see KIND_* in ram.h); signs, people
    kinds = ["Blank", "Shelter", "Food", "Homeless", "Police", "Passerby", "Item"]
    a.label("KindGfxLo")
    a.lines.append("    .byte " + ",".join(f"<{k}Gfx" for k in kinds))
    a.label("KindGfxHi")
    a.lines.append("    .byte " + ",".join(f">{k}Gfx" for k in kinds))
    a.label("KindColLo")
    a.lines.append("    .byte " + ",".join(f"<{k}Col" for k in kinds))
    a.label("KindColHi")
    a.lines.append("    .byte " + ",".join(f">{k}Col" for k in kinds))

    a.equ("START_ROOM", start[0] * 8 + start[1])
    # roof colors per (map row + band) & 7: brick, concrete, teal, slate...
    a.table("BandColors", [col(c) for c in
                           [(3, 2), (15, 3), (10, 2), (4, 2), (13, 2), (15, 2), (9, 2), (2, 3)]])

    # energy bar: blocks 1..18 from the left edge (column 0 left empty)
    p0, p1, p2 = [], [], []
    for n in range(ENERGY_BLOCKS + 1):
        cols = [0 < i <= n for i in range(20)]
        v = half_to_pf(cols)
        p0.append(v[0]); p1.append(v[1]); p2.append(v[2])
    a.table("BarPF0", p0)
    a.table("BarPF1", p1)
    a.table("BarPF2", p2)
    a.equ("ENERGY_BLOCKS", ENERGY_BLOCKS)
    a.save("bank0_data.asm")


